import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACTIONS, type AnyActionSpec } from '@devias/core';
import { loadModules } from '@devias/server';
import deviasConfig from '../../../../devias.config';
import { declaredActionSpecs } from '../actions/declared';

/** Writes docs/reference/actions.mdx from the action specs: one table per tag. */
const cell = (value: string) => value.replace(/\|/g, '\\|');

const approvalOf = (spec: AnyActionSpec) =>
  `${spec.approval === 'auto' ? 'auto' : '**ask**'}${spec.locked ? ', locked' : ''}`;

const toolOf = (spec: AnyActionSpec) => (spec.ai.tool === null ? `none: ${spec.ai.reason}` : `\`${spec.ai.tool}\``);

const flags = (spec: AnyActionSpec) =>
  [spec.sessionOnly ? 'people only' : null, spec.externalContent ? 'outside content' : null].filter(Boolean).join(', ');

const main = async () => {
  const moduleActions = declaredActionSpecs(await loadModules(deviasConfig, { from: import.meta.url }));
  const all = [...ACTIONS, ...moduleActions.map((action) => action.spec)];
  const byTag = new Map<string, AnyActionSpec[]>();

  for (const spec of all) {
    const tag = spec.module ? `${spec.module} (module)` : (spec.tags[0] ?? 'other');
    byTag.set(tag, [...(byTag.get(tag) ?? []), spec]);
  }

  const sections = [...byTag].map(([tag, specs]) => {
    const rows = specs.map(
      (spec) =>
        `| \`${spec.id}\` | \`${spec.http.method.toUpperCase()} ${spec.http.path}\` | \`${spec.permission}\` | ${approvalOf(spec)} | ${cell(toolOf(spec))} | ${flags(spec)} |`,
    );

    return [
      `## ${tag}`,
      '',
      '| Action | Route | Permission | Agent asks | Tool | Notes |',
      '| --- | --- | --- | --- | --- | --- |',
      ...rows,
    ].join('\n');
  });
  const page = [
    '---',
    'title: Actions reference',
    'description: Every action the server implements, with its route, permission, approval and the agent tool that serves it.',
    'icon: list-checks',
    '---',
    '',
    '{/* Generated by `pnpm --filter @devias/server-app actions:export` from the specs in packages/core/src/actions and the modules registered on the server. Do not edit. */}',
    '',
    `${all.length} actions: core's, and those the bundled modules declare. Each is one REST route and one agent tool (or a reason it has none); see [Actions](/architecture/actions) for how they are declared. "Agent asks" is the default approval: **ask** pauses for the person, *locked* means no workspace override can make it automatic. "People only" actions refuse API keys and automations; "outside content" results reach the model marked as untrusted.`,
    '',
    sections.join('\n\n'),
    '',
  ].join('\n');

  const here = path.dirname(fileURLToPath(import.meta.url));
  const target = path.resolve(here, '../../../../docs/reference/actions.mdx');
  writeFileSync(target, page);
  console.log(`wrote ${target} (${all.length} actions)`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
