import { coreIds, defineView } from '@devias/core';
import { ids } from './ids';

/** Saved views: invoice tables (all, outstanding), a board by status, and tables for lines and payments. */
export const views = [
  defineView({
    id: ids.views.invoice.all,
    objectId: ids.objects.invoice,
    label: 'All invoices',
    type: 'table',
    icon: 'table',
    isDefault: true,
    position: 0,
    fields: [
      { fieldId: ids.fields.invoice.total, width: 130 },
      { fieldId: ids.fields.invoice.status, width: 110 },
      { fieldId: ids.fields.invoice.number, width: 140 },
      { fieldId: ids.fields.invoice.company, width: 180 },
      { fieldId: ids.fields.invoice.due_date, width: 130 },
      { fieldId: ids.fields.invoice.issue_date, width: 130 },
      { fieldId: ids.fields.invoice.contact, width: 160 },
    ],
    sorts: [{ fieldId: coreIds.fields.created_at, direction: 'desc' }],
  }),
  defineView({
    id: ids.views.invoice.outstanding,
    objectId: ids.objects.invoice,
    label: 'Outstanding',
    type: 'table',
    icon: 'clock',
    position: 1,
    fields: [
      { fieldId: ids.fields.invoice.total, width: 130 },
      { fieldId: ids.fields.invoice.number, width: 140 },
      { fieldId: ids.fields.invoice.company, width: 180 },
      { fieldId: ids.fields.invoice.due_date, width: 130 },
      { fieldId: ids.fields.invoice.contact, width: 160 },
    ],
    filter: { field: ids.fields.invoice.status, op: 'eq', value: 'sent' },
    sorts: [{ fieldId: ids.fields.invoice.due_date, direction: 'asc' }],
  }),
  defineView({
    id: ids.views.invoice.board,
    objectId: ids.objects.invoice,
    label: 'Board',
    type: 'kanban',
    icon: 'kanban',
    position: 2,
    fields: [
      { fieldId: ids.fields.invoice.number },
      { fieldId: ids.fields.invoice.total },
      { fieldId: ids.fields.invoice.company },
      { fieldId: ids.fields.invoice.due_date },
    ],
    groupById: ids.fields.invoice.status,
    sorts: [{ fieldId: ids.fields.invoice.due_date, direction: 'asc' }],
    settings: { aggregate: { fieldId: ids.fields.invoice.total, operation: 'sum' } },
  }),
  defineView({
    id: ids.views.invoice_line.all,
    objectId: ids.objects.invoice_line,
    label: 'All lines',
    type: 'table',
    icon: 'table',
    isDefault: true,
    position: 0,
    fields: [
      { fieldId: ids.fields.invoice_line.description, width: 260 },
      { fieldId: ids.fields.invoice_line.invoice, width: 160 },
      { fieldId: ids.fields.invoice_line.quantity, width: 100 },
      { fieldId: ids.fields.invoice_line.unit_price, width: 130 },
    ],
    sorts: [{ fieldId: coreIds.fields.created_at, direction: 'asc' }],
  }),
  defineView({
    id: ids.views.payment.all,
    objectId: ids.objects.payment,
    label: 'All payments',
    type: 'table',
    icon: 'table',
    isDefault: true,
    position: 0,
    fields: [
      { fieldId: ids.fields.payment.invoice, width: 160 },
      { fieldId: ids.fields.payment.amount, width: 130 },
      { fieldId: ids.fields.payment.paid_on, width: 130 },
      { fieldId: ids.fields.payment.method, width: 140 },
      { fieldId: ids.fields.payment.reference, width: 200 },
    ],
    sorts: [{ fieldId: ids.fields.payment.paid_on, direction: 'desc' }],
  }),
];
